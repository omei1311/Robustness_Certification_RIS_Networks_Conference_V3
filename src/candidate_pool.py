"""Candidate pool generation and collection (new; Section 7 stage (i)).

The certification layer does NOT re-run the first paper's robust WEE
optimizer.  Candidate configurations are generated by a decoupled,
lightweight protocol on the shared nominal channel drop:

  1. RIS phase profile: a fraction ``align_frac`` of the elements takes the
     cascaded-channel-aligned quantized phase (two-pass heuristic), the rest
     are drawn uniformly from the B-bit discrete set Q_B (Eq. (1));
  2. beamforming directions: reused MRT or intra-cell RZF initializers;
  3. power control: a worst-case fixed-point iteration (Cauchy-Schwarz
     bounds over the per-user uncertainty ball) that meets a chosen design
     SINR target ``gamma_d >= gamma_bar`` with design radius ``eps_d``
     (eps_d = 0 -> nominal design, eps_d = epsilon -> robust design);

followed by the reused nominal QoS feasibility check and WEE evaluation.
Candidates whose power control diverges or exceeds the per-BS budget are
discarded.  The knobs (align_frac, bits, direction type, gamma_d, eps_d) are
randomized per candidate to obtain a diverse feasible pool in the
WEE-robustness plane, as required by Experiment 2.
"""

